// Exposed for tests so a parity/key-existence guard can assert en/zh coverage
// without duplicating the dictionaries. Not intended for runtime use.
export const enDictionary: Record<string, string> = en;
export const zhDictionary: Record<string, string> = zh;

export function translate(
  key: string,
  locale: StudioLocale,
  params?: Record<string, string | number>,
): string {
  const dict = locale === "en" ? en : zh;
  let value = dict[key];
  if (value === undefined) {
    if (locale !== "en") {
      value = en[key];
    }
    if (value === undefined) {
      return key;
    }
  }
  if (params) {
    for (const [param, replacement] of Object.entries(params)) {
      const pattern = new RegExp(`\\{${escapeRegExp(param)}\\}`, "g");
      value = value.replace(pattern, String(replacement));
    }
  }
  return value;
}

function escapeRegExp(input: string): string {
  return input.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// ---------------------------------------------------------------------------
// Context / Provider / Hook
// ---------------------------------------------------------------------------

interface StudioI18nContextValue {
  locale: StudioLocale;
  setLocale(locale: StudioLocale): void;
  t(key: string, params?: Record<string, string | number>): string;
}

const StudioI18nContext = createContext<StudioI18nContextValue | null>(null);

export function StudioI18nProvider({
  children,
  defaultLocale,
}: {
  children: ReactNode;
  defaultLocale?: StudioLocale;
}) {
  const [locale, setLocaleState] = useState<StudioLocale>(() =>
    defaultLocale ?? readInitialLocale(globalThis.window),
  );

  useEffect(() => {
    if (typeof document !== "undefined" && document.body) {
      document.body.dataset.locale = locale;
    }
  }, [locale]);

  const value = useMemo<StudioI18nContextValue>(
    () => ({
      locale,
      setLocale(nextLocale: StudioLocale) {
        setLocaleState(nextLocale);
        storageFor(globalThis.window)?.setItem(storageKey, nextLocale);
      },
      t(key: string, params?: Record<string, string | number>) {
        return translate(key, locale, params);
      },
    }),
    [locale],
  );

  return (
    <StudioI18nContext.Provider value={value}>
      {children}
    </StudioI18nContext.Provider>
  );
}

export function useStudioI18n() {
  const context = useContext(StudioI18nContext);
  if (!context) {
    throw new Error("StudioI18nProvider is required.");
  }
  return context;
}

export function LanguageToggle() {
  const { locale, setLocale, t } = useStudioI18n();
  return (
    <label className="inline-flex h-10 shrink-0 items-center gap-2 rounded-md border border-canvas-200/70 bg-canvas-50 px-3 text-sm font-semibold text-ink">
      <span>{t("lang.language")}</span>
      <select
        aria-label={t("lang.language")}
        value={locale}
        onChange={(event) => setLocale(event.target.value as StudioLocale)}
        className="bg-transparent text-sm font-semibold outline-none"
      >
        <option value="en">{t("lang.english")}</option>
        <option value="zh">{t("lang.chinese")}</option>
      </select>
    </label>
  );
}

function readInitialLocale(view: Window | undefined): StudioLocale {
  const stored = storageFor(view)?.getItem(storageKey);
  if (isStudioLocale(stored)) {
    return stored;
  }
  if (typeof process !== "undefined" && process.env.NODE_ENV === "test") {
    return "en";
  }
  return "zh";
}

function storageFor(view: Window | undefined): Storage | null {
  const storage = view?.localStorage;
  if (
    storage &&
    typeof storage.getItem === "function" &&
    typeof storage.setItem === "function"
  ) {
    return storage;
  }
  return null;
}

function isStudioLocale(value: string | null | undefined): value is StudioLocale {
  return value === "en" || value === "zh";
}
